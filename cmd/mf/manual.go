package main

import (
	"fmt"
	"io"
	"regexp"
	"strings"
)

var helpMetadata = regexp.MustCompile(`\s*\[(?:default|possible values|aliases):[^\]]*\]`)

func cleanDescription(text string) string {
	return strings.TrimSpace(helpMetadata.ReplaceAllString(text, ""))
}

func manualArgumentHelp(item CommandSpec, name string) string {
	section := strings.SplitN(item.Help, "Arguments:\n", 2)
	if len(section) != 2 {
		return ""
	}
	section = strings.SplitN(section[1], "\nOptions:", 2)
	pattern := regexp.MustCompile(`(?m)^  [<\[]` + regexp.QuoteMeta(name) + `[>\]](?:\.\.\.)?[ \t]*([^\n]*(?:\n {4,}[^\n]*)*)`)
	match := pattern.FindStringSubmatch(section[0])
	if len(match) != 2 {
		return ""
	}
	return cleanDescription(strings.Join(strings.Fields(match[1]), " "))
}

func manualAbout(item CommandSpec) string {
	if strings.HasPrefix(item.About, "Usage:") {
		return ""
	}
	return strings.Join(strings.Fields(item.About), " ")
}

func Manual(spec *Spec) string {
	var text strings.Builder
	text.WriteString("<!-- Generated by `mf --generate-manual`; do not edit directly. -->\n\n# Command-Line Help for `mf`\n\nThis document contains the help content for the `mf` command-line program.\n\n**Command Overview:**\n\n")
	children := map[string][]CommandSpec{}
	for _, item := range spec.Commands {
		if len(item.Path) > 0 {
			key := strings.Join(item.Path[:len(item.Path)-1], " ")
			children[key] = append(children[key], item)
		}
	}
	var ordered []CommandSpec
	var visit func(CommandSpec)
	visit = func(item CommandSpec) {
		ordered = append(ordered, item)
		for _, child := range children[strings.Join(item.Path, " ")] {
			visit(child)
		}
	}
	root, _ := spec.Lookup(nil)
	visit(root)
	for _, item := range ordered {
		name := strings.TrimSpace("mf " + strings.Join(item.Path, " "))
		fmt.Fprintf(&text, "* [`%s`↴](#%s)\n", name, strings.ReplaceAll(name, " ", "-"))
	}
	text.WriteString("\n")
	for _, item := range ordered {
		name := strings.TrimSpace("mf " + strings.Join(item.Path, " "))
		usage := item.Usage
		flags := item.Flags
		if len(item.Path) == 0 {
			flags = spec.GlobalFlags
		} else if len(flags) == 0 {
			usage = strings.ReplaceAll(usage, " [OPTIONS]", "")
		}
		fmt.Fprintf(&text, "## `%s`\n\n%s\n\n**Usage:** `mf %s`\n\n", name, manualAbout(item), usage)
		if len(item.Aliases) != 0 {
			fmt.Fprintf(&text, "**Command Alias:** `%s`\n\n", strings.Join(item.Aliases, "`, `"))
		}
		if len(item.Arguments) != 0 {
			text.WriteString("###### **Arguments:**\n\n")
			for _, argument := range item.Arguments {
				label := "<" + argument.Name + ">"
				if argument.Repeat {
					label += "..."
				}
				fmt.Fprintf(&text, "* `%s`", label)
				if description := manualArgumentHelp(item, argument.Name); description != "" {
					fmt.Fprintf(&text, " — %s", description)
				}
				text.WriteByte('\n')
				manualValues(&text, nil, argument.Choices)
			}
			text.WriteByte('\n')
		}
		if items := children[strings.Join(item.Path, " ")]; len(items) != 0 {
			text.WriteString("###### **Subcommands:**\n\n")
			for _, child := range items {
				fmt.Fprintf(&text, "* `%s` — %s\n", child.Path[len(child.Path)-1], manualAbout(child))
			}
			text.WriteByte('\n')
		}
		visible := []FlagSpec{}
		for _, flag := range flags {
			if !flag.Hidden && flag.Name != "help" && flag.Name != "version" {
				visible = append(visible, flag)
			}
		}
		if len(visible) != 0 {
			text.WriteString("###### **Options:**\n\n")
			for _, flag := range visible {
				text.WriteString("* ")
				if flag.Short != "" {
					fmt.Fprintf(&text, "`-%s`, ", flag.Short)
				}
				fmt.Fprintf(&text, "`--%s", flag.Name)
				if flag.ValueName != "" {
					fmt.Fprintf(&text, " <%s>", flag.ValueName)
				}
				text.WriteByte('`')
				if len(flag.Aliases) != 0 {
					fmt.Fprintf(&text, " [alias: `%s`]", strings.Join(flag.Aliases, "`, `"))
				}
				if description := cleanDescription(flag.Help); description != "" {
					fmt.Fprintf(&text, " — %s", description)
				}
				text.WriteByte('\n')
				manualValues(&text, flag.Default, flag.Choices)
			}
			text.WriteByte('\n')
		}
		text.WriteString("\n\n")
	}
	return strings.TrimRight(text.String(), "\n") + "\n"
}

func manualValues(text io.Writer, defaultValue *string, choices []string) {
	if defaultValue != nil {
		fmt.Fprintf(text, "\n  Default value: `%s`\n\n", *defaultValue)
	}
	if len(choices) > 0 {
		fmt.Fprintf(text, "\n  Possible values: `%s`\n\n", strings.Join(choices, "`, `"))
	}
}
